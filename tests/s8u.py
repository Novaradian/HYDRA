# UI batch: graph/overview toggles + pop-outs, side panel, movable live popup
import json, time
from playwright.sync_api import sync_playwright
import os; S=os.environ.get('HYDRA_ROOT', os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..' if os.path.basename(os.path.dirname(os.path.abspath(__file__)))=='tests' else '../..')))
R=[]
def check(n,c,x=''): R.append(('PASS' if c else 'FAIL',n,str(x)[:300]))
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1600,'height':960}); pg=ctx.new_page()
    errs=[]; pg.on('pageerror',lambda e: errs.append(str(e))); pg.on('console',lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
    pg.goto('file://'+S+'/dist/HYDRA/HYDRA.html'); pg.wait_for_timeout(2500); ev=pg.evaluate
    H="window.HYDRA"; DS="window.HYDRA.designer.st"; SIM="window.HYDRA.designer.sim"; CV="window.HYDRA.designer.canvas"
    ev(f"{H}.actions.openSampleCopy('s_basic_cyl')"); pg.wait_for_timeout(1200)
    ev(f"{DS}.dock.value={{open:false,tab:'rules'}}"); pg.wait_for_timeout(200)
    ev(f"{DS}.D.value.simRun()"); pg.wait_for_timeout(800)
    check('graph does NOT open on simulation start by default', not ev(f"{DS}.dock.value.open"), ev(f"{DS}.dock.value"))
    ev(f"{DS}.D.value.simStop()"); pg.wait_for_timeout(300)
    ev(f"{H}.S.savePrefs({{...{H}.S.prefs.value, graphAuto:true}})")
    ev(f"{DS}.D.value.simRun()"); pg.wait_for_timeout(800)
    check('pref "open graph on start": Simulation tab opens', ev(f"{DS}.dock.value.open && {DS}.dock.value.tab==='sim'"))
    gb=pg.query_selector('.hd button[title^="Graph (Simulation tab)"]')
    check('toolbar Graph toggle present and pressed', gb is not None and gb.get_attribute('aria-pressed')=='true')
    gb.click(); pg.wait_for_timeout(200); check('Graph toggle hides the graph', not ev(f"{DS}.dock.value.open"))
    gb.click(); pg.wait_for_timeout(200); check('Graph toggle shows it again', ev(f"{DS}.dock.value.open && {DS}.dock.value.tab==='sim'"))
    with ctx.expect_page() as pi: pg.click('.ddock button:has-text("Own window")')
    gw=pi.value; pg.wait_for_timeout(900)
    check('graph pop-out window shows the live list + plot', gw.query_selector('.dsimdock canvas') is not None and 'Oil' in gw.inner_text('body'), gw.inner_text('body')[:120])
    check('dock says the graph is in its own window', 'own window' in pg.inner_text('.ddock'))
    gw.close(); pg.wait_for_timeout(400)
    check('closing the window brings the graph back to the dock', pg.query_selector('.ddock .dsimdock') is not None and not ev(f"{DS}.popWins.value.graph"))
    ev(f"{DS}.D.value.simStop()"); pg.wait_for_timeout(300)
    ev(f"{H}.S.savePrefs({{...{H}.S.prefs.value, graphPop:true}})"); ev(f"{DS}.dock.value={{open:false,tab:'rules'}}")
    with ctx.expect_page(timeout=5000) as pi: pg.click('.simbtn')
    gw=pi.value; pg.wait_for_timeout(800)
    check('pref "…in its own window": graph pops out on start', gw.query_selector('.dsimdock') is not None and ev(f"{DS}.popWins.value.graph"))
    gw.close(); pg.wait_for_timeout(300); ev(f"{H}.S.savePrefs({{...{H}.S.prefs.value, graphPop:false, graphAuto:false}})")
    # overview
    check('overview shown by default', pg.query_selector('.dcanvas .dminimap svg') is not None or pg.query_selector('.dminimap svg') is not None)
    ob=pg.query_selector('.hd button[title="Overview on / off"]'); ob.click(); pg.wait_for_timeout(200)
    check('Overview toggle hides it (collapsed chip)', pg.query_selector('.dminimap:not(.shut) svg') is None and pg.query_selector('.dminimap.shut') is not None)
    check('overview off is saved to preferences', ev(f"{H}.S.prefs.value.overview")==False)
    ob.click(); pg.wait_for_timeout(200); check('Overview toggle shows it again', pg.query_selector('.dminimap svg') is not None)
    with ctx.expect_page() as pi: pg.click('.dmmbar button[title^="Open the overview"]')
    ow=pi.value; pg.wait_for_timeout(800)
    svg=ow.query_selector('.dpopov svg'); bb=svg.bounding_box() if svg else None
    check('overview pop-out: large map in its own window, small one hidden', bb and bb['width']>300 and pg.query_selector('.dminimap') is None, bb)
    v0=ev(f"(()=>{{const v={DS}.views.get({DS}.D.value.sheetId); return v?[v.px,v.py]:null}})()")
    ow.mouse.click(bb['x']+bb['width']*0.15, bb['y']+bb['height']*0.2); pg.wait_for_timeout(300)
    v1=ev(f"(()=>{{const v={DS}.views.get({DS}.D.value.sheetId); return v?[v.px,v.py]:null}})()")
    check('click in the overview window pans the main sheet', v1 and v1!=v0, (v0,v1))
    ow.close(); pg.wait_for_timeout(300); check('overview returns after closing its window', pg.query_selector('.dminimap svg') is not None)
    # movable live popup
    ev(f"{DS}.D.value.simRun()"); pg.wait_for_timeout(800)
    key=ev(f"[...{SIM}.SIM.live.keys()][0]")
    ev(f"{CV}.liveOpen.value={{key:'{key}',x:200,y:120}}"); pg.wait_for_timeout(300)
    lp=pg.query_selector('.dlivepop'); b0=lp.bounding_box()
    h=pg.query_selector('.dlivepop .h.drag').bounding_box()
    pg.mouse.move(h['x']+60,h['y']+8); pg.mouse.down(); pg.mouse.move(h['x']+460,h['y']+308,steps=8); pg.mouse.up(); pg.wait_for_timeout(200)
    b1=pg.query_selector('.dlivepop').bounding_box()
    check('live popup moves by dragging its title', abs(b1['x']-b0['x']-400)<6 and abs(b1['y']-b0['y']-300)<6, (b0,b1))
    check('position remembered', ev(f"{DS}.livePos.value") is not None)
    ev(f"{CV}.liveOpen.value=null"); pg.wait_for_timeout(100); ev(f"{CV}.liveOpen.value={{key:'{key}',x:50,y:40}}"); pg.wait_for_timeout(200)
    b2=pg.query_selector('.dlivepop').bounding_box()
    check('reopened popup (another click) stays where it was put', abs(b2['x']-b1['x'])<2 and abs(b2['y']-b1['y'])<2)
    pg.click('.dlivepop button[title="Collapse"]'); pg.wait_for_timeout(150)
    check('collapse hides the sliders', pg.query_selector('.dlivepop .row') is None)
    pg.click('.dlivepop button[title="Expand"]'); pg.wait_for_timeout(150)
    check('expand shows them again', pg.query_selector('.dlivepop .row') is not None)
    pg.click('.dlivepop button[title="Back beside the part"]'); pg.wait_for_timeout(150)
    b3=pg.query_selector('.dlivepop').bounding_box(); check('pin button puts it back beside the part', abs(b3['x']-b2['x'])>50)
    pg.screenshot(path=S+'/ui_live.png')
    ev(f"{CV}.liveOpen.value=null"); ev(f"{DS}.D.value.simStop()"); pg.wait_for_timeout(300)
    # side panel
    ev(f"{H}.actions.openSampleCopy('s_sequence')"); pg.wait_for_timeout(1200)
    pg.add_script_tag(path=S+'/tests/t8/seqprog.js'); P="window.HYDRA.plc"; L="window.HYDRA.plc.state"
    sheet=ev(f"{DS}.D.value.sheetId")
    pid=ev(f"{H}.S.addNode('program', null, undefined, 'Auto_Cycle')")
    ev(f"(()=>{{const T={P}.signals.signals({H}.S.project.value); {L}.writeProg('{pid}', x=>{{ x.ws=mkSeqProg(T); x.active=true; }}); }})()")
    ev(f"{H}.cmds.runCmd('menu.controller')"); pg.wait_for_timeout(700); pg.click('.hd button:has-text("Auto-build from project")'); pg.wait_for_timeout(800)
    ev(f"{H}.S.openSheetTab('{sheet}')"); pg.wait_for_timeout(900)
    if not ev(f"{DS}.panes.value.right"): ev(f"{DS}.D.value.togglePane('right')")
    pg.wait_for_timeout(200)
    pg.click('.dright .dtabs button:has-text("Panel")'); pg.wait_for_timeout(500)
    check('right sidebar has a Panel tab showing the operator panel', pg.query_selector('.dright .opn') is not None, pg.inner_text('.dright')[:200])
    w=pg.query_selector('.dright').bounding_box()['width']; check('sidebar widens for the panel', w>400, w)
    check('circuit stays visible beside it', pg.query_selector('.dcanvas') is not None and pg.query_selector('.dcanvas').bounding_box()['width']>600)
    pg.click('.dright .op-stopped button'); pg.wait_for_timeout(800)
    check('Start machine from the side panel runs PLC + hydraulics', ev(f"{L}.RT.value.rt.state")=='running' and ev(f"!!{SIM}.simView.value"))
    pg.wait_for_timeout(1500); pg.screenshot(path=S+'/ui_sidepanel.png')
    check('no second panel dock while the side tab shows it', pg.query_selector('.opdock') is None)
    pg.click('.dright .dtabs button:has-text("Properties")'); pg.wait_for_timeout(200)
    check('back to Properties: the running panel moves to its usual dock', pg.query_selector('.opdock .opn') is not None)
    ev(f"{L}.stop()"); pg.wait_for_timeout(400)
    check('stopped: Properties at normal width', pg.query_selector('.dright').bounding_box()['width']<340)
    check('no page errors', not [e for e in errs if 'favicon' not in e], errs[:5])
    b.close()
for r in R: print(*r)
print(sum(1 for r in R if r[0]=='PASS'),'/',len(R))
